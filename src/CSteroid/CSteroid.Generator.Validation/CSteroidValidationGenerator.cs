using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using CSteroid.Generator.Shared;
using static CSteroid.Generator.Shared.AttributeFormatter;
using static CSteroid.Generator.Shared.GeneratorConstants;
using static CSteroid.Generator.Shared.NestedTargets;
using static CSteroid.Generator.Shared.OutputConventions;
using static CSteroid.Generator.Shared.SourceTextHelper;

namespace CSteroid.Generator.Validation
{
    [Generator]
    public class CSteroidValidationGenerator : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterSourceOutput(InterfaceDiscovery.Register(context), Execute);
        }

        private static void Execute(SourceProductionContext spc, (ImmutableArray<INamedTypeSymbol> Symbols, Compilation Compilation) source)
        {
            InterfaceDiscovery.ExecuteWithErrorBoundary(spc, () => ExecuteCore(spc, source));
        }

        private static void ExecuteCore(SourceProductionContext spc, (ImmutableArray<INamedTypeSymbol> Symbols, Compilation Compilation) source)
        {
            var modelInfos = InterfaceDiscovery.BuildModelInfos(spc, source.Symbols, source.Compilation);
            if (modelInfos.Count == 0)
                return;

            var fileNamingConvention = GetFileNamingConvention(source.Compilation.Assembly);
            var (validationNamespace, _) = GetOutputNamespaces(source.Compilation.Assembly);
            var policy = EmissionPolicy.For(source.Compilation);

            // Group first so each target emits exactly one validator; the group's first entry
            // is the canonical declaration (duplicate target declarations on multiple
            // interfaces share the validator). Only local targets are emitted.
            var validatorGroups = modelInfos
                .Where(m => (m.ValidationType & ValidationTypeCustom) != 0 && policy.IsLocal(m))
                .GroupBy(m => m.Target, StringComparer.Ordinal)
                .OrderBy(g => g.Key, StringComparer.Ordinal)
                .ToList();

            var validatorTargets = new Dictionary<string, ModelInfo>(StringComparer.Ordinal);
            foreach (var g in validatorGroups)
            {
                validatorTargets[g.Key] = g.OrderBy(m => m.Target, StringComparer.Ordinal).First();
            }

            foreach (var group in validatorGroups)
            {
                var info = validatorTargets[group.Key];

                var validatorNamespace = GetValidationNamespace(info, validationNamespace);
                var validatorSource = GenerateValidator(info, validatorTargets, validatorNamespace);
                var validatorHintPath = GetOutputHintPath(validatorNamespace, DefaultValidationNamespace, GetFileName($"{info.Target}Validator", fileNamingConvention));
                spc.AddSource(validatorHintPath, ToSourceText(validatorSource));
            }
        }

        #region Validator Generation

        private static string GenerateValidator(ModelInfo info, Dictionary<string, ModelInfo> validatorTargets, string validationNamespace)
        {
            var sb = new StringBuilder();
            var modelNamespace = GetModelNamespace(info);
            var isAsync = (info.ValidationType & ValidationTypeAsync) != 0;

            var validatorTargetNames = new HashSet<string>(validatorTargets.Keys, StringComparer.Ordinal);
            var nestedWiring = new Dictionary<string, (string NestedTarget, bool IsCollection)>(StringComparer.Ordinal);
            foreach (var prop in info.Properties)
            {
                if (nestedWiring.ContainsKey(prop.Name))
                    continue;

                if (TryGetNestedTarget(prop.Type, validatorTargetNames, out var nestedTarget))
                    nestedWiring[prop.Name] = (nestedTarget, false);
                else if (TryGetCollectionElementTarget(prop.Type, validatorTargetNames, out var elementTarget, out _))
                    nestedWiring[prop.Name] = (elementTarget, true);
            }

            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("#pragma warning disable CS8618, CS8669 // generated models: reference properties are intentionally uninitialized");
            sb.AppendLine("using System;");
            if (isAsync)
            {
                sb.AppendLine("using System.Threading;");
            }
            sb.AppendLine("using System.Threading.Tasks;");
            sb.AppendLine("using CSteroid;");
            if (modelNamespace != validationNamespace)
            {
                sb.AppendLine($"using {modelNamespace};");
            }

            var nestedNamespaces = new SortedSet<string>(StringComparer.Ordinal);
            foreach (var wiring in nestedWiring.Values)
            {
                var nestedInfo = validatorTargets[wiring.NestedTarget];
                nestedNamespaces.Add(GetModelNamespace(nestedInfo));
                nestedNamespaces.Add(GetValidationNamespace(nestedInfo, validationNamespace));
            }

            foreach (var ns in nestedNamespaces)
            {
                if (ns != validationNamespace && ns != modelNamespace)
                {
                    sb.AppendLine($"using {ns};");
                }
            }

            sb.AppendLine();
            sb.AppendLine($"namespace {validationNamespace}");
            sb.AppendLine("{");
            sb.AppendLine($"    {GeneratorMetadata.AttributeLine}");
            sb.AppendLine($"    internal partial class {info.Target}Validator : {(isAsync ? $"global::CSteroid.IAsyncValidator<{info.Target}>" : $"global::CSteroid.IValidator<{info.Target}>")}");
            sb.AppendLine("    {");
            sb.AppendLine($"        private static Action<IRuleBuilder<{info.Target}>>? _customRulesAction;");
            sb.AppendLine("        private static bool _replaceDefaults;");
            sb.AppendLine($"        private static readonly {(isAsync ? "Async" : string.Empty)}RuleBuilder<{info.Target}> s_ruleBuilder;");
            sb.AppendLine();
            sb.AppendLine($"        static {info.Target}Validator()");
            sb.AppendLine("        {");
            sb.AppendLine($"            ValidatorRegistry.Register<{info.Target}>(new {info.Target}Validator());");
            foreach (var nestedTarget in nestedWiring.Values.Select(w => w.NestedTarget).Distinct(StringComparer.Ordinal).OrderBy(n => n, StringComparer.Ordinal))
            {
                sb.AppendLine($"            ValidatorRegistry.Register<{nestedTarget}>(new {nestedTarget}Validator());");
            }
            sb.AppendLine($"            ConfigureValidation(new ValidationConfiguration<{info.Target}>(");
            sb.AppendLine($"                action => _customRulesAction = action,");
            sb.AppendLine("                replace => _replaceDefaults = replace));");
            sb.AppendLine();
            sb.AppendLine($"            var builder = new {(isAsync ? "Async" : string.Empty)}RuleBuilder<{info.Target}>();");
            sb.AppendLine("            if (!_replaceDefaults)");
            sb.AppendLine("                BuildDefaultRules(builder);");
            sb.AppendLine("            _customRulesAction?.Invoke(builder);");
            sb.AppendLine("            s_ruleBuilder = builder;");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine("        static partial void ConfigureValidation(ValidationConfiguration<" + info.Target + "> config);");
            sb.AppendLine();
            if (isAsync)
            {
                sb.AppendLine($"        public ValidationResult Validate({info.Target} model)");
                sb.AppendLine("        {");
                sb.AppendLine($"            throw new InvalidOperationException(\"{info.Target}Validator contains async rules. Call ValidateAsync instead.\");");
                sb.AppendLine("        }");
                sb.AppendLine();
                sb.AppendLine($"        public async Task<ValidationResult> ValidateAsync({info.Target} model, CancellationToken cancellationToken = default)");
                sb.AppendLine("        {");
                sb.AppendLine($"            return await s_ruleBuilder.ValidateAsync(model, cancellationToken).ConfigureAwait(false);");
                sb.AppendLine("        }");
            }
            else
            {
                sb.AppendLine($"        public ValidationResult Validate({info.Target} model)");
                sb.AppendLine("        {");
                sb.AppendLine("            return s_ruleBuilder.Validate(model);");
                sb.AppendLine("        }");
                sb.AppendLine();
                sb.AppendLine($"        public Task<ValidationResult> ValidateAsync({info.Target} model)");
                sb.AppendLine("        {");
                sb.AppendLine("            return Task.FromResult(Validate(model));");
                sb.AppendLine("        }");
            }
            sb.AppendLine();
            sb.AppendLine($"        private static void BuildDefaultRules(IRuleBuilder<{info.Target}> rules)");
            sb.AppendLine("        {");
            GenerateDefaultValidationRules(sb, info, nestedWiring);
            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        private static void GenerateDefaultValidationRules(StringBuilder sb, ModelInfo info, Dictionary<string, (string NestedTarget, bool IsCollection)> nestedWiring)
        {
            foreach (var prop in info.Properties)
            {
                var chain = new StringBuilder();

                foreach (var attr in prop.GetAttributes().OrderBy(a => a.AttributeClass?.ToDisplayString() ?? string.Empty, StringComparer.Ordinal))
                {
                    var className = attr.AttributeClass?.Name;
                    if (className is null)
                        continue;

                    var errorMessage = GetAttributeNamedArgument(attr, "ErrorMessage") as string;

                    switch (className)
                    {
                        case "RequiredAttribute":
                            chain.Append(".NotNull()");
                            AppendValidationRule(chain, ".NotEmpty()", errorMessage);
                            break;
                        case "MaxLengthAttribute":
                            if (GetAttributeConstructorArgument(attr, 0) is int maxLength)
                            {
                                AppendValidationRule(chain, $".MaxLength({maxLength})", errorMessage);
                            }
                            else if (GetAttributeNamedArgument(attr, "Length") is int maxLengthNamed)
                            {
                                AppendValidationRule(chain, $".MaxLength({maxLengthNamed})", errorMessage);
                            }
                            break;
                        case "MinLengthAttribute":
                            if (GetAttributeConstructorArgument(attr, 0) is int minLength)
                            {
                                AppendValidationRule(chain, $".MinLength({minLength})", errorMessage);
                            }
                            break;
                        case "StringLengthAttribute":
                            if (GetAttributeConstructorArgument(attr, 0) is int stringLengthMax)
                            {
                                if (GetAttributeNamedArgument(attr, "MinimumLength") is int minStringLength)
                                {
                                    AppendValidationRule(chain, $".MinLength({minStringLength})", null);
                                }
                                AppendValidationRule(chain, $".MaxLength({stringLengthMax})", errorMessage);
                            }
                            else if (GetAttributeNamedArgument(attr, "MaximumLength") is int stringLengthMaxNamed)
                            {
                                if (GetAttributeNamedArgument(attr, "MinimumLength") is int minStringLengthNamed)
                                {
                                    AppendValidationRule(chain, $".MinLength({minStringLengthNamed})", null);
                                }
                                AppendValidationRule(chain, $".MaxLength({stringLengthMaxNamed})", errorMessage);
                            }
                            break;
                        case "RangeAttribute":
                            var rangeMin = GetAttributeConstructorArgument(attr, 0);
                            var rangeMax = GetAttributeConstructorArgument(attr, 1);
                            if (rangeMin != null && rangeMax != null)
                            {
                                AppendValidationRule(chain, $".InclusiveBetween({FormatLiteral(rangeMin)}, {FormatLiteral(rangeMax)})", errorMessage);
                            }
                            break;
                        case "RegularExpressionAttribute":
                            if (GetAttributeConstructorArgument(attr, 0) is string pattern)
                            {
                                AppendValidationRule(chain, $".Matches(\"{EscapeString(pattern)}\")", errorMessage);
                            }
                            break;
                        case "EmailAddressAttribute":
                            AppendValidationRule(chain, ".EmailAddress()", errorMessage);
                            break;
                        case "PhoneAttribute":
                            AppendValidationRule(chain, ".Matches(@\"^\\+?[0-9\\s\\-().]+$\")", errorMessage);
                            break;
                        case "UrlAttribute":
                            AppendValidationRule(chain, ".Must(v => global::System.Uri.TryCreate(v, global::System.UriKind.Absolute, out _), \"Must be a valid URL.\")", errorMessage);
                            break;
                    }
                }

                if (chain.Length > 0)
                {
                    sb.AppendLine($"            rules.For(x => x.{prop.Name}){chain};");
                }

                if (nestedWiring.TryGetValue(prop.Name, out var wiring))
                {
                    sb.AppendLine(wiring.IsCollection
                        ? $"            rules.ForEachNested(x => x.{prop.Name});"
                        : $"            rules.ForNested(x => x.{prop.Name});");
                }
            }
        }

        private static void AppendValidationRule(StringBuilder chain, string rule, string errorMessage)
        {
            chain.Append(rule);
            if (!string.IsNullOrEmpty(errorMessage))
            {
                chain.Append($".WithMessage(\"{EscapeString(errorMessage)}\")");
            }
        }

        #endregion
    }
}
