using System;
using System.Collections.Generic;
using CSteroid.Generator.Shared;
using Microsoft.CodeAnalysis;

namespace CSteroid.Generator.Medium
{
    internal static class MediatorEmitter
    {
        internal static void Emit(SourceProductionContext context, EmissionPlan plan)
        {
            if (!plan.IsCompositionRoot)
                return;

            context.AddSource(
                "Medium.Mediator.g.cs",
                SourceTextHelper.ToSourceText(Emit(plan)));
        }

        internal static string Emit(EmissionPlan plan)
        {
            if (!plan.IsCompositionRoot)
                return string.Empty;

            var responseRoutes = new List<RoutePlan>();
            var commandRoutes = new List<RoutePlan>();
            var eventRoutes = new List<List<RoutePlan>>();

            foreach (var route in plan.Routes)
            {
                switch (route.Kind)
                {
                    case RouteKind.CommandWithResponse:
                        responseRoutes.Add(route);
                        break;
                    case RouteKind.Command:
                        commandRoutes.Add(route);
                        break;
                    case RouteKind.Message:
                        if (eventRoutes.Count == 0
                            || !string.Equals(
                                eventRoutes[eventRoutes.Count - 1][0].Message.RouteKey,
                                route.Message.RouteKey,
                                StringComparison.Ordinal))
                        {
                            eventRoutes.Add(new List<RoutePlan>());
                        }
                        eventRoutes[eventRoutes.Count - 1].Add(route);
                        break;
                }
            }

            var writer = new CodeWriter();
            WriteHeader(writer);
            writer.OpenBlock("namespace CSteroid.Medium");
            writer.AppendLine("[global::System.CodeDom.Compiler.GeneratedCode(\"CSteroid.Medium\", \"1.0.0\")]");
            writer.OpenBlock("internal sealed class GeneratedMedium : global::CSteroid.Medium.IMedium");
            writer.AppendLine("private readonly global::System.IServiceProvider _services;");
            writer.AppendLine();
            writer.OpenBlock("public GeneratedMedium(global::System.IServiceProvider services)");
            writer.AppendLine("_services = services;");
            writer.CloseBlock();

            if (responseRoutes.Count != 0)
            {
                writer.AppendLine();
                EmitResponseTable(writer, responseRoutes);
            }
            if (commandRoutes.Count != 0)
            {
                writer.AppendLine();
                EmitCommandTable(writer, commandRoutes);
            }
            if (eventRoutes.Count != 0)
            {
                writer.AppendLine();
                EmitPublishTable(writer, eventRoutes);
            }

            writer.AppendLine();
            EmitResponseSend(writer, responseRoutes.Count != 0);
            writer.AppendLine();
            EmitCommandSend(writer, commandRoutes.Count != 0);
            writer.AppendLine();
            EmitPublish(writer, eventRoutes.Count != 0);

            foreach (var route in responseRoutes)
            {
                writer.AppendLine();
                EmitCommandRoute(writer, route);
            }
            foreach (var route in commandRoutes)
            {
                writer.AppendLine();
                EmitCommandRoute(writer, route);
            }
            foreach (var group in eventRoutes)
            {
                writer.AppendLine();
                EmitPublishRoute(writer, group);
            }

            writer.CloseBlock();
            writer.CloseBlock();
            return writer.ToString();
        }

        private static void WriteHeader(CodeWriter writer)
        {
            writer.AppendLine("// <auto-generated />");
            writer.AppendLine("#nullable enable");
            writer.AppendLine();
        }

        private static void EmitResponseTable(CodeWriter writer, List<RoutePlan> routes)
        {
            writer.AppendLine("private delegate global::System.Threading.Tasks.ValueTask<TResponse> __MED_ResponseDispatch<TResponse>(GeneratedMedium medium, global::CSteroid.Medium.ICommand<TResponse> command, global::System.Threading.CancellationToken cancellationToken);");
            writer.AppendLine();
            writer.OpenBlock("private static readonly global::System.Collections.Generic.Dictionary<global::System.Type, global::System.Delegate> __med_responseRoutes = new global::System.Collections.Generic.Dictionary<global::System.Type, global::System.Delegate>");
            foreach (var route in routes)
            {
                writer.AppendLine("{ typeof(" + route.Message.GlobalName + "), new __MED_ResponseDispatch<" + ResponseType(route) + ">(__MED_Dispatch_" + route.MemberId + ") },");
            }
            writer.CloseBlock(";");
        }

        private static void EmitCommandTable(CodeWriter writer, List<RoutePlan> routes)
        {
            writer.AppendLine("private delegate global::System.Threading.Tasks.ValueTask __MED_CommandDispatch(GeneratedMedium medium, global::CSteroid.Medium.ICommand command, global::System.Threading.CancellationToken cancellationToken);");
            writer.AppendLine();
            writer.OpenBlock("private static readonly global::System.Collections.Generic.Dictionary<global::System.Type, __MED_CommandDispatch> __med_commandRoutes = new global::System.Collections.Generic.Dictionary<global::System.Type, __MED_CommandDispatch>");
            foreach (var route in routes)
            {
                writer.AppendLine("{ typeof(" + route.Message.GlobalName + "), new __MED_CommandDispatch(__MED_Dispatch_" + route.MemberId + ") },");
            }
            writer.CloseBlock(";");
        }

        private static void EmitPublishTable(
            CodeWriter writer,
            List<List<RoutePlan>> eventRoutes)
        {
            writer.AppendLine("private delegate global::System.Threading.Tasks.ValueTask __MED_PublishDispatch(GeneratedMedium medium, global::CSteroid.Medium.IMessage message, global::System.Threading.CancellationToken cancellationToken);");
            writer.AppendLine();
            writer.OpenBlock("private static readonly global::System.Collections.Generic.Dictionary<global::System.Type, __MED_PublishDispatch> __med_publishRoutes = new global::System.Collections.Generic.Dictionary<global::System.Type, __MED_PublishDispatch>");
            foreach (var subscribers in eventRoutes)
            {
                var route = subscribers[0];
                writer.AppendLine("{ typeof(" + route.Message.GlobalName + "), new __MED_PublishDispatch(__MED_Dispatch_Publish_" + PublishMemberId(route.Message.RouteKey) + ") },");
            }
            writer.CloseBlock(";");
        }

        private static void EmitResponseSend(CodeWriter writer, bool hasRoutes)
        {
            writer.OpenBlock("public global::System.Threading.Tasks.ValueTask<TResponse> Send<TResponse>(global::CSteroid.Medium.ICommand<TResponse> command, global::System.Threading.CancellationToken cancellationToken = default)");
            writer.OpenBlock("if (command is null)");
            writer.AppendLine("throw new global::System.ArgumentNullException(nameof(command));");
            writer.CloseBlock();
            writer.AppendLine();
            if (hasRoutes)
            {
                writer.OpenBlock("if (__med_responseRoutes.TryGetValue(command.GetType(), out var route))");
                writer.AppendLine("return ((__MED_ResponseDispatch<TResponse>)route)(this, command, cancellationToken);");
                writer.CloseBlock();
                writer.AppendLine();
            }
            writer.AppendLine("throw new global::System.InvalidOperationException(\"No exact Medium response-command route for \" + command.GetType().FullName + \".\");");
            writer.CloseBlock();
        }

        private static void EmitCommandSend(CodeWriter writer, bool hasRoutes)
        {
            writer.OpenBlock("public global::System.Threading.Tasks.ValueTask Send(global::CSteroid.Medium.ICommand command, global::System.Threading.CancellationToken cancellationToken = default)");
            writer.OpenBlock("if (command is null)");
            writer.AppendLine("throw new global::System.ArgumentNullException(nameof(command));");
            writer.CloseBlock();
            writer.AppendLine();
            if (hasRoutes)
            {
                writer.OpenBlock("if (__med_commandRoutes.TryGetValue(command.GetType(), out var route))");
                writer.AppendLine("return route(this, command, cancellationToken);");
                writer.CloseBlock();
                writer.AppendLine();
            }
            writer.AppendLine("throw new global::System.InvalidOperationException(\"No exact Medium command route for \" + command.GetType().FullName + \".\");");
            writer.CloseBlock();
        }

        private static void EmitPublish(CodeWriter writer, bool hasRoutes)
        {
            writer.OpenBlock("public global::System.Threading.Tasks.ValueTask Publish(global::CSteroid.Medium.IMessage message, global::System.Threading.CancellationToken cancellationToken = default)");
            writer.OpenBlock("if (message is null)");
            writer.AppendLine("throw new global::System.ArgumentNullException(nameof(message));");
            writer.CloseBlock();
            writer.AppendLine();
            writer.OpenBlock("if (message is global::CSteroid.Medium.ICommand)");
            writer.AppendLine("throw new global::System.ArgumentException(\"Medium Publish does not accept commands; use Send instead.\", nameof(message));");
            writer.CloseBlock();
            writer.AppendLine();
            if (hasRoutes)
            {
                writer.OpenBlock("if (__med_publishRoutes.TryGetValue(message.GetType(), out var route))");
                writer.AppendLine("return route(this, message, cancellationToken);");
                writer.CloseBlock();
                writer.AppendLine();
            }
            writer.AppendLine("throw new global::System.InvalidOperationException(\"No exact Medium publish route for \" + message.GetType().FullName + \".\");");
            writer.CloseBlock();
        }

        private static void EmitCommandRoute(CodeWriter writer, RoutePlan route)
        {
            var returnType = ReturnType(route);
            var commandInterface = route.Kind == RouteKind.CommandWithResponse
                ? "global::CSteroid.Medium.ICommand<" + ResponseType(route) + ">"
                : "global::CSteroid.Medium.ICommand";
            var pipelineName = "__MED_Send_" + route.MemberId;
            var terminalName = pipelineName + "Terminal";
            var continuationName = "__med_send_" + route.MemberId + "Terminal";

            writer.AppendLine("private static " + returnType + " __MED_Dispatch_" + route.MemberId + "(GeneratedMedium medium, " + commandInterface + " command, global::System.Threading.CancellationToken cancellationToken)");
            writer.AppendLine("    => medium." + pipelineName + "((" + route.Message.GlobalName + ")command, cancellationToken);");
            writer.AppendLine();
            EmitPipeline(writer, route, pipelineName, "command", terminalName, continuationName);
            writer.AppendLine();
            EmitHandlerTerminal(writer, route, terminalName, "command");
        }

        private static void EmitPublishRoute(CodeWriter writer, List<RoutePlan> subscribers)
        {
            var first = subscribers[0];
            var memberId = PublishMemberId(first.Message.RouteKey);
            var pipelineName = "__MED_Publish_" + memberId;
            var fanoutName = pipelineName + "Fanout";
            var continuationName = "__med_publish_" + memberId + "Fanout";

            writer.AppendLine("private static global::System.Threading.Tasks.ValueTask __MED_Dispatch_Publish_" + memberId + "(GeneratedMedium medium, global::CSteroid.Medium.IMessage message, global::System.Threading.CancellationToken cancellationToken)");
            writer.AppendLine("    => medium." + pipelineName + "((" + first.Message.GlobalName + ")message, cancellationToken);");
            writer.AppendLine();
            EmitPipeline(writer, first, pipelineName, "message", fanoutName, continuationName);
            writer.AppendLine();

            if (subscribers.Count == 1)
            {
                writer.AppendLine("private static global::System.Threading.Tasks.ValueTask " + fanoutName + "(global::System.IServiceProvider services, " + first.Message.GlobalName + " message, global::System.Threading.CancellationToken cancellationToken)");
                writer.AppendLine("    => " + PublishTerminalName(subscribers[0]) + "(services, message, cancellationToken);");
            }
            else
            {
                writer.OpenBlock("private static async global::System.Threading.Tasks.ValueTask " + fanoutName + "(global::System.IServiceProvider services, " + first.Message.GlobalName + " message, global::System.Threading.CancellationToken cancellationToken)");
                foreach (var subscriber in subscribers)
                {
                    writer.AppendLine("await " + PublishTerminalName(subscriber) + "(services, message, cancellationToken).ConfigureAwait(false);");
                }
                writer.CloseBlock();
            }

            foreach (var subscriber in subscribers)
            {
                writer.AppendLine();
                EmitHandlerTerminal(writer, subscriber, PublishTerminalName(subscriber), "message");
            }
        }

        private static void EmitPipeline(
            CodeWriter writer,
            RoutePlan route,
            string methodName,
            string parameterName,
            string terminalName,
            string continuationName)
        {
            var nextType = NextType(route);
            if (route.Behaviors.Count != 0)
            {
                writer.AppendLine("private " + nextType + "? " + continuationName + ";");
                writer.AppendLine();
            }

            writer.OpenBlock("private " + ReturnType(route) + " " + methodName + "(" + route.Message.GlobalName + " " + parameterName + ", global::System.Threading.CancellationToken cancellationToken)");
            if (route.Behaviors.Count == 0)
            {
                writer.AppendLine("return " + terminalName + "(_services, " + parameterName + ", cancellationToken);");
                writer.CloseBlock();
                return;
            }

            writer.AppendLine("var __med_next0 = " + continuationName + ";");
            writer.OpenBlock("if (__med_next0 is null)");
            writer.AppendLine("__med_next0 = " + methodName + "Continuation;");
            writer.AppendLine(continuationName + " = __med_next0;");
            writer.CloseBlock();
            writer.AppendLine();

            var step = 0;
            for (var index = route.Behaviors.Count - 1; index >= 0; index--)
            {
                var behavior = route.Behaviors[index];
                var behaviorName = "__med_behavior" + step;
                writer.AppendLine("var " + behaviorName + " =");
                writer.AppendLine("    (" + BehaviorInterfaceType(route) + ")");
                writer.AppendLine("    global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<" + behavior.BehaviorType.GlobalName + ">(_services);");
                writer.AppendLine(nextType + " __med_next" + (step + 1) + " =");
                writer.AppendLine("    (message, ct) => " + behaviorName + ".Handle(message, __med_next" + step + ", ct);");
                writer.AppendLine();
                step++;
            }

            writer.AppendLine("return __med_next" + step + "(" + parameterName + ", cancellationToken);");
            writer.CloseBlock();
            writer.AppendLine();
            writer.AppendLine("private " + ReturnType(route) + " " + methodName + "Continuation(" + route.Message.GlobalName + " message, global::System.Threading.CancellationToken cancellationToken)");
            writer.AppendLine("    => " + terminalName + "(_services, message, cancellationToken);");
        }

        private static void EmitHandlerTerminal(
            CodeWriter writer,
            RoutePlan route,
            string methodName,
            string parameterName)
        {
            string handlerInterface;
            if (route.Kind == RouteKind.CommandWithResponse)
            {
                handlerInterface = "global::CSteroid.Medium.ICommandHandler<" + route.Message.GlobalName + ", " + ResponseType(route) + ">";
            }
            else if (route.Kind == RouteKind.Command)
            {
                handlerInterface = "global::CSteroid.Medium.ICommandHandler<" + route.Message.GlobalName + ">";
            }
            else
            {
                handlerInterface = "global::CSteroid.Medium.IMessageHandler<" + route.Message.GlobalName + ">";
            }

            writer.OpenBlock("private static " + ReturnType(route) + " " + methodName + "(global::System.IServiceProvider services, " + route.Message.GlobalName + " " + parameterName + ", global::System.Threading.CancellationToken cancellationToken)");
            writer.AppendLine("var handler =");
            writer.AppendLine("    (" + handlerInterface + ")");
            writer.AppendLine("    global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<" + route.HandlerType.GlobalName + ">(services);");
            writer.AppendLine("return handler.Handle(" + parameterName + ", cancellationToken);");
            writer.CloseBlock();
        }

        private static string PublishTerminalName(RoutePlan route) =>
            "__MED_Publish_" + route.MemberId + "Terminal";

        private static string PublishMemberId(string routeKey) => StableName.Hash(routeKey);

        private static string ResponseType(RoutePlan route) => route.Response!.GlobalName;

        private static string ReturnType(RoutePlan route) =>
            route.Kind == RouteKind.CommandWithResponse
                ? "global::System.Threading.Tasks.ValueTask<" + ResponseType(route) + ">"
                : "global::System.Threading.Tasks.ValueTask";

        private static string NextType(RoutePlan route) =>
            route.Kind == RouteKind.CommandWithResponse
                ? "global::CSteroid.Medium.MediumNext<" + route.Message.GlobalName + ", " + ResponseType(route) + ">"
                : "global::CSteroid.Medium.MediumNext<" + route.Message.GlobalName + ">";

        private static string BehaviorInterfaceType(RoutePlan route) =>
            route.Kind == RouteKind.CommandWithResponse
                ? "global::CSteroid.Medium.IPipelineBehavior<" + route.Message.GlobalName + ", " + ResponseType(route) + ">"
                : "global::CSteroid.Medium.IPipelineBehavior<" + route.Message.GlobalName + ">";
    }
