using System;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace CSteroid.Generator.Medium
{
    internal static partial class FactsReader
    {
        internal static AddMediumUseFact? ReadAddMediumUse(
            InvocationExpressionSyntax invocation,
            SemanticModel semanticModel)
        {
            if (invocation.ArgumentList.Arguments.Count != 0
                || invocation.Expression is not MemberAccessExpressionSyntax member
                || member.Name is not IdentifierNameSyntax name
                || !string.Equals(name.Identifier.ValueText, "AddMedium", StringComparison.Ordinal))
            {
                return null;
            }

            var serviceCollection = semanticModel.Compilation.GetTypeByMetadataName(
                "Microsoft.Extensions.DependencyInjection.IServiceCollection");
            if (serviceCollection is null
                || semanticModel.GetTypeInfo(member.Expression).Type is not { } receiverType)
            {
                return null;
            }
            var conversion = semanticModel.Compilation.ClassifyCommonConversion(receiverType, serviceCollection);
            if (!conversion.Exists || !conversion.IsImplicit)
                return null;

            var symbolInfo = semanticModel.GetSymbolInfo(invocation);
            if (symbolInfo.Symbol is IMethodSymbol method)
            {
                return IsGeneratedAddMedium(method, semanticModel.Compilation, serviceCollection)
                    ? new AddMediumUseFact(CreateLocation(invocation.SyntaxTree, invocation.Span))
                    : null;
            }

            foreach (var candidate in symbolInfo.CandidateSymbols)
            {
                if (candidate is not IMethodSymbol candidateMethod
                    || !IsGeneratedAddMedium(candidateMethod, semanticModel.Compilation, serviceCollection))
                {
                    return null;
                }
            }
            return new AddMediumUseFact(CreateLocation(invocation.SyntaxTree, invocation.Span));
        }

        private static bool IsGeneratedAddMedium(
            IMethodSymbol method,
            Compilation compilation,
            INamedTypeSymbol serviceCollection)
        {
            method = method.ReducedFrom ?? method;
            if (!method.IsStatic
                || !method.IsExtensionMethod
                || !string.Equals(method.Name, "AddMedium", StringComparison.Ordinal)
                || method.Parameters.Length != 1
                || !SymbolEqualityComparer.Default.Equals(method.Parameters[0].Type, serviceCollection)
                || !SymbolEqualityComparer.Default.Equals(method.ReturnType, serviceCollection)
                || method.ContainingType is not { IsStatic: true } containingType
                || !string.Equals(containingType.Name, "MediumGeneratedRegistration", StringComparison.Ordinal)
                || !string.Equals(containingType.ContainingNamespace?.ToDisplayString(), "CSteroid.Medium", StringComparison.Ordinal)
                || !SymbolEqualityComparer.Default.Equals(containingType.ContainingAssembly, compilation.Assembly))
            {
                return false;
            }

            foreach (var reference in method.DeclaringSyntaxReferences)
            {
                var leadingText = reference.SyntaxTree.GetRoot().GetLeadingTrivia().ToFullString();
                if (leadingText.IndexOf("<auto-generated", StringComparison.Ordinal) >= 0)
                    return true;
            }
            return false;
        }
    }
}
