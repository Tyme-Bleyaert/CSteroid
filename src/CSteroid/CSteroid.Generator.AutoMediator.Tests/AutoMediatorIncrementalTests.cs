using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace CSteroid.Generator.AutoMediator.Tests;

public class AutoMediatorIncrementalTests
{
    [Fact]
    public void RepeatedRunsAndShuffledTrees_ProduceByteIdenticalStableUtf8LfOutput()
    {
        var compilation = AutoMediatorTestCompilation.Create(
            """
            using CSteroid.AutoMediator;
            [assembly: AutoMediatorCompositionRoot]
            public sealed class Command : ICommand<int> { }
            public sealed class Notice : IMessage { }
            """,
            """
            using System.Threading;
            using System.Threading.Tasks;
            using CSteroid.AutoMediator;
            public sealed class ZetaHandler : ICommandHandler<Command, int>
            {
                public ValueTask<int> Handle(Command command, CancellationToken cancellationToken) => new(1);
            }
            public sealed class AlphaHandler : IMessageHandler<Notice>
            {
                public ValueTask Handle(Notice message, CancellationToken cancellationToken) => default;
            }
            """);

        var first = Snapshots(Run(AutoMediatorExecution.CreateDriver(), compilation, out _).GetRunResult());
        var repeated = Snapshots(Run(AutoMediatorExecution.CreateDriver(), compilation, out _).GetRunResult());
        var shuffledCompilation = CSharpCompilation.Create(
            compilation.AssemblyName,
            compilation.SyntaxTrees.Reverse(),
            compilation.References,
            compilation.Options);
        var shuffled = Snapshots(Run(AutoMediatorExecution.CreateDriver(), shuffledCompilation, out _).GetRunResult());

        Assert.Equal(first, repeated);
        Assert.Equal(first, shuffled);
        Assert.Equal(first.Length, first.Select(snapshot => snapshot.HintName).Distinct(StringComparer.Ordinal).Count());
        Assert.All(first, snapshot =>
        {
            Assert.Equal(65001, snapshot.CodePage);
            Assert.DoesNotContain("\r", snapshot.Text);
            Assert.StartsWith("// <auto-generated />", snapshot.Text);
            Assert.Contains("#nullable enable", snapshot.Text);
        });
    }

    [Fact]
    public void UnrelatedAndSendOnlyEdits_DoNotChangeGeneratedOutputOrCachedPlans()
    {
        var compilation = AutoMediatorTestCompilation.Create(
            """
            using CSteroid.AutoMediator;
            [assembly: AutoMediatorCompositionRoot]
            public sealed class Command : ICommand { }
            """,
            """
            using System.Threading;
            using System.Threading.Tasks;
            using CSteroid.AutoMediator;
            public sealed class Handler : ICommandHandler<Command>
            {
                public ValueTask Handle(Command command, CancellationToken cancellationToken) => default;
            }
            """,
            """
            using CSteroid.AutoMediator;
            public sealed class Consumer
            {
                public void Call(ISender sender) => _ = sender.Send(new Command());
            }
            """);
        var driver = Run(AutoMediatorExecution.CreateDriver(trackIncrementalSteps: true), compilation, out _);
        var expected = Snapshots(driver.GetRunResult());
        AutoMediatorTrackedSteps.AssertInitial(driver);
        var originalConsumer = compilation.SyntaxTrees.Single(tree => tree.FilePath == "2.cs");

        var unrelatedEdit = CSharpSyntaxTree.ParseText(
            """
            using CSteroid.AutoMediator;
            public sealed class Consumer
            {
                public int UnrelatedProperty { get; set; }
                public void Call(ISender sender) => _ = sender.Send(new Command());
            }
            """,
            path: originalConsumer.FilePath);
        var unrelatedCompilation = compilation.ReplaceSyntaxTree(originalConsumer, unrelatedEdit);
        driver = Run(driver, unrelatedCompilation, out _);
        Assert.Equal(expected, Snapshots(driver.GetRunResult()));
        AutoMediatorTrackedSteps.AssertRetained(driver);

        var sendOnlyEdit = CSharpSyntaxTree.ParseText(
            """
            using CSteroid.AutoMediator;
            public sealed class Consumer
            {
                public int UnrelatedProperty { get; set; }
                public void Call(ISender sender)
                {
                    _ = sender.Send(new Command());
                    _ = sender.Send(new Command());
                }
            }
            """,
            path: originalConsumer.FilePath);
        driver = Run(driver, unrelatedCompilation.ReplaceSyntaxTree(unrelatedEdit, sendOnlyEdit), out _);
        Assert.Equal(expected, Snapshots(driver.GetRunResult()));
        AutoMediatorTrackedSteps.AssertRetained(driver);
    }

    [Fact]
    public void RemovingInterfaceThenHandler_RemovesOnlyStaleRoutesAndRegistrations()
    {
        const string rootAndMessages = """
            using CSteroid.AutoMediator;
            [assembly: AutoMediatorCompositionRoot]
            public sealed class FirstCommand : ICommand { }
            public sealed class SecondNotice : IMessage { }
            public sealed class SurvivingCommand : ICommand<int> { }
            """;
        const string originalHandlers = """
            using System.Threading;
            using System.Threading.Tasks;
            using CSteroid.AutoMediator;
            public sealed class MultiHandler : ICommandHandler<FirstCommand>, IMessageHandler<SecondNotice>
            {
                public ValueTask Handle(FirstCommand command, CancellationToken cancellationToken) => default;
                public ValueTask Handle(SecondNotice message, CancellationToken cancellationToken) => default;
            }
            public sealed class SurvivingHandler : ICommandHandler<SurvivingCommand, int>
            {
                public ValueTask<int> Handle(SurvivingCommand command, CancellationToken cancellationToken) => new(1);
            }
            """;
        var compilation = AutoMediatorTestCompilation.Create(rootAndMessages, originalHandlers);
        var driver = Run(AutoMediatorExecution.CreateDriver(), compilation, out _);
        var handlerTree = compilation.SyntaxTrees.Single(tree => tree.FilePath == "1.cs");

        var oneInterface = CSharpSyntaxTree.ParseText(
            """
            using System.Threading;
            using System.Threading.Tasks;
            using CSteroid.AutoMediator;
            public sealed class MultiHandler : ICommandHandler<FirstCommand>
            {
                public ValueTask Handle(FirstCommand command, CancellationToken cancellationToken) => default;
            }
            public sealed class SurvivingHandler : ICommandHandler<SurvivingCommand, int>
            {
                public ValueTask<int> Handle(SurvivingCommand command, CancellationToken cancellationToken) => new(1);
            }
            """,
            path: handlerTree.FilePath);
        var oneInterfaceCompilation = compilation.ReplaceSyntaxTree(handlerTree, oneInterface);
        driver = Run(driver, oneInterfaceCompilation, out _);
        var mediator = Mediator(driver);
        Assert.Contains("FirstCommand", mediator);
        Assert.DoesNotContain("SecondNotice", mediator);
        Assert.Contains("SurvivingCommand", mediator);
        Assert.Contains("TryAddScoped<global::MultiHandler>(services)", GeneratedText(driver));

        var removed = CSharpSyntaxTree.ParseText(
            """
            using System.Threading;
            using System.Threading.Tasks;
            using CSteroid.AutoMediator;
            public sealed class SurvivingHandler : ICommandHandler<SurvivingCommand, int>
            {
                public ValueTask<int> Handle(SurvivingCommand command, CancellationToken cancellationToken) => new(1);
            }
            """,
            path: handlerTree.FilePath);
        driver = Run(driver, oneInterfaceCompilation.ReplaceSyntaxTree(oneInterface, removed), out _);
        mediator = Mediator(driver);
        var generated = GeneratedText(driver);
        Assert.DoesNotContain("FirstCommand", mediator);
        Assert.DoesNotContain("MultiHandler", generated);
        Assert.Contains("SurvivingCommand", mediator);
        Assert.Contains("TryAddScoped<global::SurvivingHandler>(services)", generated);
    }

    private static GeneratorDriver Run(GeneratorDriver driver, Compilation compilation, out Compilation output)
    {
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out output, out var diagnostics);
        Assert.Empty(diagnostics);
        AutoMediatorExecution.AssertCompiles(output);
        return driver;
    }

    private static Snapshot[] Snapshots(GeneratorDriverRunResult result) =>
        Assert.Single(result.Results).GeneratedSources
            .Select(source => new Snapshot(source.HintName, source.SourceText.ToString(), source.SourceText.Encoding!.CodePage))
            .ToArray();

    private static string Mediator(GeneratorDriver driver) =>
        Assert.Single(Assert.Single(driver.GetRunResult().Results).GeneratedSources,
            source => source.SourceText.ToString().Contains("class GeneratedAutoMediator"))
            .SourceText.ToString();

    private static string GeneratedText(GeneratorDriver driver) =>
        string.Join("\n", Assert.Single(driver.GetRunResult().Results).GeneratedSources.Select(source => source.SourceText.ToString()));

    private sealed record Snapshot(string HintName, string Text, int CodePage);
}
