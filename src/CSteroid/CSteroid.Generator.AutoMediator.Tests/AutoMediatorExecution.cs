using System.Collections.Immutable;
using System.Reflection;
using System.Runtime.Loader;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;

namespace CSteroid.Generator.AutoMediator.Tests;

internal static class AutoMediatorExecution
{
    internal static GeneratorDriver CreateDriver(bool trackIncrementalSteps = false) =>
        CSharpGeneratorDriver.Create(
            new[] { new global::CSteroid.Generator.AutoMediator.AutoMediatorGenerator().AsSourceGenerator() },
            driverOptions: new GeneratorDriverOptions(IncrementalGeneratorOutputKind.None, trackIncrementalSteps));

    internal static Compilation RunGenerator(
        Compilation compilation,
        out ImmutableArray<Diagnostic> generatorDiagnostics,
        bool assertCompiles = true)
    {
        CreateDriver().RunGeneratorsAndUpdateCompilation(compilation, out var output, out generatorDiagnostics);
        if (assertCompiles)
            AssertCompiles(output);
        return output;
    }

    internal static Task<ImmutableArray<Diagnostic>> Analyze(string source) =>
        Analyze(AutoMediatorTestCompilation.Create(source));

    internal static Task<ImmutableArray<Diagnostic>> Analyze(Compilation compilation) =>
        compilation.WithAnalyzers(ImmutableArray.Create<DiagnosticAnalyzer>(
            new global::CSteroid.Generator.AutoMediator.AutoMediatorDiagnosticAnalyzer()))
            .GetAnalyzerDiagnosticsAsync();

    internal static void AssertCompiles(Compilation compilation)
    {
        var errors = compilation.GetDiagnostics()
            .Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error)
            .ToArray();
        Assert.True(errors.Length == 0, string.Join(Environment.NewLine, errors.Select(diagnostic => diagnostic.ToString())));
    }

    internal static byte[] EmitImage(Compilation compilation)
    {
        using var stream = new MemoryStream();
        var result = compilation.Emit(stream);
        Assert.True(result.Success, string.Join(Environment.NewLine, result.Diagnostics.Select(diagnostic => diagnostic.ToString())));
        return stream.ToArray();
    }

    internal static Assembly Emit(Compilation compilation) => Assembly.Load(EmitImage(compilation));

    internal static MetadataReference EmitMetadataReference(Compilation compilation) =>
        MetadataReference.CreateFromImage(EmitImage(compilation));

    internal static Task<T> RunProgramAsync<T>(
        byte[] rootImage,
        params (string Name, byte[] Image)[] dependencies)
    {
        var context = new InMemoryLoadContext(dependencies);
        using var stream = new MemoryStream(rootImage, writable: false);
        return RunProgramAsync<T>(context.LoadFromStream(stream));
    }

    internal static async Task<T> RunProgramAsync<T>(Assembly assembly)
    {
        var program = assembly.GetType("Program", throwOnError: true)!;
        var run = program.GetMethod("Run", BindingFlags.Public | BindingFlags.Static)!;
        object? invocation;
        try
        {
            invocation = run.Invoke(null, null);
        }
        catch (TargetInvocationException exception) when (exception.InnerException is not null)
        {
            throw exception.InnerException;
        }
        return await (Task<T>)invocation!;
    }

    internal static int Count(string text, string value)
    {
        var count = 0;
        for (var index = 0; (index = text.IndexOf(value, index, StringComparison.Ordinal)) >= 0; index += value.Length)
            count++;
        return count;
    }

    internal static string[] GeneratedSources(Compilation compilation) =>
        compilation.SyntaxTrees
            .Where(tree => tree.GetRoot().GetLeadingTrivia().ToFullString().Contains("<auto-generated"))
            .OrderBy(tree => tree.FilePath, StringComparer.Ordinal)
            .Select(tree => tree.ToString())
            .ToArray();

    private sealed class InMemoryLoadContext : AssemblyLoadContext
    {
        private readonly Dictionary<string, byte[]> _dependencies;

        internal InMemoryLoadContext(IEnumerable<(string Name, byte[] Image)> dependencies)
        {
            _dependencies = dependencies.ToDictionary(item => item.Name, item => item.Image, StringComparer.OrdinalIgnoreCase);
        }

        protected override Assembly? Load(AssemblyName assemblyName)
        {
            if (assemblyName.Name is not { } name || !_dependencies.TryGetValue(name, out var image))
                return null;
            using var stream = new MemoryStream(image, writable: false);
            return LoadFromStream(stream);
        }
    }
}
