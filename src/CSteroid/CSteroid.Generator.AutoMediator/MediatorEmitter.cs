using System;
using System.Collections.Generic;
using CSteroid.Generator.Shared;
using Microsoft.CodeAnalysis;

namespace CSteroid.Generator.AutoMediator
{
    internal static class MediatorEmitter
    {
        internal static void Emit(SourceProductionContext context, EmissionPlan plan)
        {
            if (!plan.IsCompositionRoot)
                return;

            context.AddSource(
                "AutoMediator.Mediator.g.cs",
                SourceTextHelper.ToSourceText(Emit(plan)));
        }

        internal static string Emit(EmissionPlan plan)
        {
            if (!plan.IsCompositionRoot)
                return string.Empty;

            var responseRoutes = new List<RoutePlan>();
            var commandRoutes = new List<RoutePlan>();
            var eventRoutes = new SortedDictionary<string, List<RoutePlan>>(StringComparer.Ordinal);

            foreach (var route in plan.Routes)
            {
                switch (route.Kind)
                {
                    case RouteKind.CommandWithResponse:
                        responseRoutes.Add(route);
                        break;
                    case RouteKind.Command:
                        commandRoutes.Add(route);
                        break;
                    case RouteKind.Message:
                        if (!eventRoutes.TryGetValue(route.Message.RouteKey, out var subscribers))
                        {
                            subscribers = new List<RoutePlan>();
                            eventRoutes.Add(route.Message.RouteKey, subscribers);
                        }
                        subscribers.Add(route);
                        break;
                }
            }

            responseRoutes.Sort(static (left, right) => CompareRoutes(left, right));
            commandRoutes.Sort(static (left, right) => CompareRoutes(left, right));
            foreach (var group in eventRoutes)
            {
                group.Value.Sort(static (left, right) => CompareSubscribers(left, right));
            }

            var writer = new CodeWriter();
            WriteHeader(writer);
            writer.OpenBlock("namespace CSteroid.AutoMediator");
            writer.AppendLine("[global::System.CodeDom.Compiler.GeneratedCode(\"CSteroid.AutoMediator\", \"1.0.0\")]");
            writer.OpenBlock("internal sealed class GeneratedAutoMediator : global::CSteroid.AutoMediator.IAutoMediator");
            writer.AppendLine("private readonly global::System.IServiceProvider _services;");
            writer.AppendLine();
            writer.OpenBlock("public GeneratedAutoMediator(global::System.IServiceProvider services)");
            writer.AppendLine("_services = services;");
            writer.CloseBlock();

            if (responseRoutes.Count != 0)
            {
                writer.AppendLine();
                EmitResponseTable(writer, responseRoutes);
            }
            if (commandRoutes.Count != 0)
            {
                writer.AppendLine();
                EmitCommandTable(writer, commandRoutes);
            }
            if (eventRoutes.Count != 0)
            {
                writer.AppendLine();
                EmitPublishTable(writer, eventRoutes);
            }

            writer.AppendLine();
            EmitResponseSend(writer, responseRoutes.Count != 0);
            writer.AppendLine();
            EmitCommandSend(writer, commandRoutes.Count != 0);
            writer.AppendLine();
            EmitPublish(writer, eventRoutes.Count != 0);

            foreach (var route in responseRoutes)
            {
                writer.AppendLine();
                EmitCommandRoute(writer, route);
            }
            foreach (var route in commandRoutes)
            {
                writer.AppendLine();
                EmitCommandRoute(writer, route);
            }
            foreach (var group in eventRoutes)
            {
                writer.AppendLine();
                EmitPublishRoute(writer, group.Value);
            }

            writer.CloseBlock();
            writer.CloseBlock();
            return writer.ToString();
        }

        private static int CompareRoutes(RoutePlan left, RoutePlan right)
        {
            var result = string.CompareOrdinal(left.Message.RouteKey, right.Message.RouteKey);
            return result != 0 ? result : string.CompareOrdinal(left.MemberId, right.MemberId);
        }

        private static int CompareSubscribers(RoutePlan left, RoutePlan right)
        {
            var result = string.CompareOrdinal(left.HandlerType.RouteKey, right.HandlerType.RouteKey);
            return result != 0 ? result : string.CompareOrdinal(left.MemberId, right.MemberId);
        }

        private static void WriteHeader(CodeWriter writer)
        {
            writer.AppendLine("// <auto-generated />");
            writer.AppendLine("#nullable enable");
            writer.AppendLine();
        }

        private static void EmitResponseTable(CodeWriter writer, List<RoutePlan> routes)
        {
            writer.AppendLine("private delegate global::System.Threading.Tasks.ValueTask<TResponse> __AM_ResponseDispatch<TResponse>(global::System.IServiceProvider services, global::CSteroid.AutoMediator.ICommand<TResponse> command, global::System.Threading.CancellationToken cancellationToken);");
            writer.AppendLine();
            writer.OpenBlock("private static readonly global::System.Collections.Generic.Dictionary<global::System.Type, global::System.Delegate> __am_responseRoutes = new global::System.Collections.Generic.Dictionary<global::System.Type, global::System.Delegate>");
            foreach (var route in routes)
            {
                writer.AppendLine("{ typeof(" + route.Message.GlobalName + "), new __AM_ResponseDispatch<" + ResponseType(route) + ">(__AM_Dispatch_" + route.MemberId + ") },");
            }
            writer.CloseBlock(";");
        }

        private static void EmitCommandTable(CodeWriter writer, List<RoutePlan> routes)
        {
            writer.AppendLine("private delegate global::System.Threading.Tasks.ValueTask __AM_CommandDispatch(global::System.IServiceProvider services, global::CSteroid.AutoMediator.ICommand command, global::System.Threading.CancellationToken cancellationToken);");
            writer.AppendLine();
            writer.OpenBlock("private static readonly global::System.Collections.Generic.Dictionary<global::System.Type, __AM_CommandDispatch> __am_commandRoutes = new global::System.Collections.Generic.Dictionary<global::System.Type, __AM_CommandDispatch>");
            foreach (var route in routes)
            {
                writer.AppendLine("{ typeof(" + route.Message.GlobalName + "), new __AM_CommandDispatch(__AM_Dispatch_" + route.MemberId + ") },");
            }
            writer.CloseBlock(";");
        }

        private static void EmitPublishTable(
            CodeWriter writer,
            SortedDictionary<string, List<RoutePlan>> eventRoutes)
        {
            writer.AppendLine("private delegate global::System.Threading.Tasks.ValueTask __AM_PublishDispatch(global::System.IServiceProvider services, global::CSteroid.AutoMediator.IMessage message, global::System.Threading.CancellationToken cancellationToken);");
            writer.AppendLine();
            writer.OpenBlock("private static readonly global::System.Collections.Generic.Dictionary<global::System.Type, __AM_PublishDispatch> __am_publishRoutes = new global::System.Collections.Generic.Dictionary<global::System.Type, __AM_PublishDispatch>");
            foreach (var group in eventRoutes)
            {
                var route = group.Value[0];
                writer.AppendLine("{ typeof(" + route.Message.GlobalName + "), new __AM_PublishDispatch(__AM_Dispatch_Publish_" + PublishMemberId(group.Key) + ") },");
            }
            writer.CloseBlock(";");
        }

        private static void EmitResponseSend(CodeWriter writer, bool hasRoutes)
        {
            writer.OpenBlock("public global::System.Threading.Tasks.ValueTask<TResponse> Send<TResponse>(global::CSteroid.AutoMediator.ICommand<TResponse> command, global::System.Threading.CancellationToken cancellationToken = default)");
            writer.OpenBlock("if (command is null)");
            writer.AppendLine("throw new global::System.ArgumentNullException(nameof(command));");
            writer.CloseBlock();
            writer.AppendLine();
            if (hasRoutes)
            {
                writer.OpenBlock("if (__am_responseRoutes.TryGetValue(command.GetType(), out var route))");
                writer.AppendLine("return ((__AM_ResponseDispatch<TResponse>)route)(_services, command, cancellationToken);");
                writer.CloseBlock();
                writer.AppendLine();
            }
            writer.AppendLine("throw new global::System.InvalidOperationException(\"No exact AutoMediator response-command route for \" + command.GetType().FullName + \".\");");
            writer.CloseBlock();
        }

        private static void EmitCommandSend(CodeWriter writer, bool hasRoutes)
        {
            writer.OpenBlock("public global::System.Threading.Tasks.ValueTask Send(global::CSteroid.AutoMediator.ICommand command, global::System.Threading.CancellationToken cancellationToken = default)");
            writer.OpenBlock("if (command is null)");
            writer.AppendLine("throw new global::System.ArgumentNullException(nameof(command));");
            writer.CloseBlock();
            writer.AppendLine();
            if (hasRoutes)
            {
                writer.OpenBlock("if (__am_commandRoutes.TryGetValue(command.GetType(), out var route))");
                writer.AppendLine("return route(_services, command, cancellationToken);");
                writer.CloseBlock();
                writer.AppendLine();
            }
            writer.AppendLine("throw new global::System.InvalidOperationException(\"No exact AutoMediator command route for \" + command.GetType().FullName + \".\");");
            writer.CloseBlock();
        }

        private static void EmitPublish(CodeWriter writer, bool hasRoutes)
        {
            writer.OpenBlock("public global::System.Threading.Tasks.ValueTask Publish(global::CSteroid.AutoMediator.IMessage message, global::System.Threading.CancellationToken cancellationToken = default)");
            writer.OpenBlock("if (message is null)");
            writer.AppendLine("throw new global::System.ArgumentNullException(nameof(message));");
            writer.CloseBlock();
            writer.AppendLine();
            writer.OpenBlock("if (message is global::CSteroid.AutoMediator.ICommand)");
            writer.AppendLine("throw new global::System.ArgumentException(\"AutoMediator Publish does not accept commands; use Send instead.\", nameof(message));");
            writer.CloseBlock();
            writer.AppendLine();
            if (hasRoutes)
            {
                writer.OpenBlock("if (__am_publishRoutes.TryGetValue(message.GetType(), out var route))");
                writer.AppendLine("return route(_services, message, cancellationToken);");
                writer.CloseBlock();
                writer.AppendLine();
            }
            writer.AppendLine("throw new global::System.InvalidOperationException(\"No exact AutoMediator publish route for \" + message.GetType().FullName + \".\");");
            writer.CloseBlock();
        }

        private static void EmitCommandRoute(CodeWriter writer, RoutePlan route)
        {
            var returnType = ReturnType(route);
            var commandInterface = route.Kind == RouteKind.CommandWithResponse
                ? "global::CSteroid.AutoMediator.ICommand<" + ResponseType(route) + ">"
                : "global::CSteroid.AutoMediator.ICommand";
            var pipelineName = "__AM_Send_" + route.MemberId;
            var terminalName = pipelineName + "Terminal";

            writer.AppendLine("private static " + returnType + " __AM_Dispatch_" + route.MemberId + "(global::System.IServiceProvider services, " + commandInterface + " command, global::System.Threading.CancellationToken cancellationToken)");
            writer.AppendLine("    => " + pipelineName + "(services, (" + route.Message.GlobalName + ")command, cancellationToken);");
            writer.AppendLine();
            EmitPipeline(writer, route, pipelineName, "command", terminalName);
            writer.AppendLine();
            EmitHandlerTerminal(writer, route, terminalName, "command");
        }

        private static void EmitPublishRoute(CodeWriter writer, List<RoutePlan> subscribers)
        {
            var first = subscribers[0];
            var memberId = PublishMemberId(first.Message.RouteKey);
            var pipelineName = "__AM_Publish_" + memberId;
            var fanoutName = pipelineName + "Fanout";

            writer.AppendLine("private static global::System.Threading.Tasks.ValueTask __AM_Dispatch_Publish_" + memberId + "(global::System.IServiceProvider services, global::CSteroid.AutoMediator.IMessage message, global::System.Threading.CancellationToken cancellationToken)");
            writer.AppendLine("    => " + pipelineName + "(services, (" + first.Message.GlobalName + ")message, cancellationToken);");
            writer.AppendLine();
            EmitPipeline(writer, first, pipelineName, "message", fanoutName);
            writer.AppendLine();

            if (subscribers.Count == 1)
            {
                writer.AppendLine("private static global::System.Threading.Tasks.ValueTask " + fanoutName + "(global::System.IServiceProvider services, " + first.Message.GlobalName + " message, global::System.Threading.CancellationToken cancellationToken)");
                writer.AppendLine("    => " + PublishTerminalName(subscribers[0]) + "(services, message, cancellationToken);");
            }
            else
            {
                writer.OpenBlock("private static async global::System.Threading.Tasks.ValueTask " + fanoutName + "(global::System.IServiceProvider services, " + first.Message.GlobalName + " message, global::System.Threading.CancellationToken cancellationToken)");
                foreach (var subscriber in subscribers)
                {
                    writer.AppendLine("await " + PublishTerminalName(subscriber) + "(services, message, cancellationToken).ConfigureAwait(false);");
                }
                writer.CloseBlock();
            }

            foreach (var subscriber in subscribers)
            {
                writer.AppendLine();
                EmitHandlerTerminal(writer, subscriber, PublishTerminalName(subscriber), "message");
            }
        }

        private static void EmitPipeline(
            CodeWriter writer,
            RoutePlan route,
            string methodName,
            string parameterName,
            string terminalName)
        {
            writer.OpenBlock("private static " + ReturnType(route) + " " + methodName + "(global::System.IServiceProvider services, " + route.Message.GlobalName + " " + parameterName + ", global::System.Threading.CancellationToken cancellationToken)");
            if (route.Behaviors.Count == 0)
            {
                writer.AppendLine("return " + terminalName + "(services, " + parameterName + ", cancellationToken);");
                writer.CloseBlock();
                return;
            }

            var nextType = NextType(route);
            writer.AppendLine(nextType + " __am_next0 =");
            writer.AppendLine("    (message, ct) => " + terminalName + "(services, message, ct);");
            writer.AppendLine();

            var step = 0;
            for (var index = route.Behaviors.Count - 1; index >= 0; index--)
            {
                var behavior = route.Behaviors[index];
                var behaviorName = "__am_behavior" + step;
                writer.AppendLine("var " + behaviorName + " =");
                writer.AppendLine("    (" + BehaviorInterfaceType(route) + ")");
                writer.AppendLine("    global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<" + behavior.BehaviorType.GlobalName + ">(services);");
                writer.AppendLine(nextType + " __am_next" + (step + 1) + " =");
                writer.AppendLine("    (message, ct) => " + behaviorName + ".Handle(message, __am_next" + step + ", ct);");
                writer.AppendLine();
                step++;
            }

            writer.AppendLine("return __am_next" + step + "(" + parameterName + ", cancellationToken);");
            writer.CloseBlock();
        }

        private static void EmitHandlerTerminal(
            CodeWriter writer,
            RoutePlan route,
            string methodName,
            string parameterName)
        {
            string handlerInterface;
            if (route.Kind == RouteKind.CommandWithResponse)
            {
                handlerInterface = "global::CSteroid.AutoMediator.ICommandHandler<" + route.Message.GlobalName + ", " + ResponseType(route) + ">";
            }
            else if (route.Kind == RouteKind.Command)
            {
                handlerInterface = "global::CSteroid.AutoMediator.ICommandHandler<" + route.Message.GlobalName + ">";
            }
            else
            {
                handlerInterface = "global::CSteroid.AutoMediator.IMessageHandler<" + route.Message.GlobalName + ">";
            }

            writer.OpenBlock("private static " + ReturnType(route) + " " + methodName + "(global::System.IServiceProvider services, " + route.Message.GlobalName + " " + parameterName + ", global::System.Threading.CancellationToken cancellationToken)");
            writer.AppendLine("var handler =");
            writer.AppendLine("    (" + handlerInterface + ")");
            writer.AppendLine("    global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<" + route.HandlerType.GlobalName + ">(services);");
            writer.AppendLine("return handler.Handle(" + parameterName + ", cancellationToken);");
            writer.CloseBlock();
        }

        private static string PublishTerminalName(RoutePlan route) =>
            "__AM_Publish_" + route.MemberId + "Terminal";

        private static string PublishMemberId(string routeKey) => StableName.Hash(routeKey);

        private static string ResponseType(RoutePlan route) => route.Response!.GlobalName;

        private static string ReturnType(RoutePlan route) =>
            route.Kind == RouteKind.CommandWithResponse
                ? "global::System.Threading.Tasks.ValueTask<" + ResponseType(route) + ">"
                : "global::System.Threading.Tasks.ValueTask";

        private static string NextType(RoutePlan route) =>
            route.Kind == RouteKind.CommandWithResponse
                ? "global::CSteroid.AutoMediator.AutoMediatorNext<" + route.Message.GlobalName + ", " + ResponseType(route) + ">"
                : "global::CSteroid.AutoMediator.AutoMediatorNext<" + route.Message.GlobalName + ">";

        private static string BehaviorInterfaceType(RoutePlan route) =>
            route.Kind == RouteKind.CommandWithResponse
                ? "global::CSteroid.AutoMediator.IPipelineBehavior<" + route.Message.GlobalName + ", " + ResponseType(route) + ">"
                : "global::CSteroid.AutoMediator.IPipelineBehavior<" + route.Message.GlobalName + ">";
    }
