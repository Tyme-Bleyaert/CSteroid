using System;
using System.Collections.Generic;
using CSteroid.Generator.Shared;
using Microsoft.CodeAnalysis;

namespace CSteroid.Generator.AutoMediator
{
    internal static class ManifestEmitter
    {
        internal static void Emit(SourceProductionContext context, LocalManifestPlan plan)
        {
            if (plan.HandlerTypes.Count == 0)
                return;

            context.AddSource(
                "AutoMediator.Manifest.g.cs",
                SourceTextHelper.ToSourceText(Emit(plan)));
        }

        internal static string Emit(LocalManifestPlan plan)
        {
            if (plan.HandlerTypes.Count == 0)
                return string.Empty;

            var handlerTypes = new SortedDictionary<string, TypeRef>(StringComparer.Ordinal);
            foreach (var handlerType in plan.HandlerTypes)
            {
                if (!handlerTypes.ContainsKey(handlerType.RouteKey))
                    handlerTypes.Add(handlerType.RouteKey, handlerType);
            }

            var writer = new CodeWriter();
            writer.AppendLine("// <auto-generated />");
            writer.AppendLine("#nullable enable");
            writer.AppendLine();
            writer.AppendLine("[assembly: global::System.CodeDom.Compiler.GeneratedCode(\"CSteroid.AutoMediator\", \"1.0.0\")]");
            foreach (var handlerType in handlerTypes.Values)
            {
                writer.AppendLine("[assembly: global::CSteroid.AutoMediator.AutoMediatorManifest(1, typeof(" + handlerType.GlobalName + "))]");
            }
            return writer.ToString();
        }
    }
}
