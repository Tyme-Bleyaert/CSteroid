    [Generator]
    public partial class CSteroidMappingGenerator : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterSourceOutput(InterfaceDiscovery.Register(context), Execute);
        }

        private static void Execute(SourceProductionContext spc, (ImmutableArray<INamedTypeSymbol> Symbols, Compilation Compilation) source)
        {
            InterfaceDiscovery.ExecuteWithErrorBoundary(spc, () => ExecuteCore(spc, source));
        }

        private static void ExecuteCore(SourceProductionContext spc, (ImmutableArray<INamedTypeSymbol> Symbols, Compilation Compilation) source)
        {
            var modelInfos = InterfaceDiscovery.BuildModelInfos(spc, source.Symbols, source.Compilation);
            if (modelInfos.Count == 0)
                return;

            var (_, mappingNamespace) = GetOutputNamespaces(source.Compilation.Assembly);
            var policy = EmissionPolicy.For(source.Compilation);

            var targetNames = new HashSet<string>(modelInfos.Select(m => m.Target), StringComparer.Ordinal);

            var byInterface = modelInfos
                .GroupBy(m => m.InterfaceSymbol, SymbolEqualityComparer.Default)
                .ToList();

            var nestedGraph = BuildNestedTargetGraph(byInterface, targetNames);
            ReportCircularReferenceDiagnostics(spc, nestedGraph);

            var mappingCode = GenerateMappings(byInterface, targetNames, spc, mappingNamespace, source.Compilation, policy);
            if (!string.IsNullOrWhiteSpace(mappingCode))
            {
                var mappingHintPath = GetOutputHintPath(mappingNamespace, DefaultMappingsNamespace, "CSteroidMappings.g.cs");
                spc.AddSource(mappingHintPath, ToSourceText(mappingCode));
            }

            var castOperatorsByNamespace = GenerateCastOperatorsByNamespace(byInterface, mappingNamespace, targetNames, nestedGraph, source.Compilation, policy);
            foreach (var kvp in castOperatorsByNamespace)
            {
                string ns = kvp.Key;
                string castCode = kvp.Value;
                string castHintName = ns == ModelsNamespace
                    ? "CSteroidCastOperators.g.cs"
                    : $"{ns.Replace('.', '/')}/CSteroidCastOperators.g.cs";
                spc.AddSource(castHintName, ToSourceText(castCode));
            }
        }

        #region Mapping Generation

        private static string GenerateMappings(List<IGrouping<ISymbol, ModelInfo>> byInterface, HashSet<string> targetNames, SourceProductionContext spc, string mappingNamespace, Compilation compilation, EmissionPolicy policy)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("#pragma warning disable CS8618, CS8669 // generated models: reference properties are intentionally uninitialized");
            sb.AppendLine("using System;");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("using System.Linq;");
            sb.AppendLine("using System.Linq.Expressions;");
            bool hasAnyMappings = false;
            var emittedModelNamespaces = new HashSet<string>(StringComparer.Ordinal);

            var nestedGraph = BuildNestedTargetGraph(byInterface, targetNames);
            var targetInfo = byInterface.SelectMany(g => g).ToDictionary(m => m.Target, StringComparer.Ordinal);

            var mapperInstances = new List<(string fieldName, string mapperType)>();
            var emittedMapperClasses = new HashSet<string>(StringComparer.Ordinal);
            var extensionMethods = new StringBuilder();
            var staticMethods = new StringBuilder();
            var projectionMethods = new StringBuilder();
            var mapperClasses = new StringBuilder();
            var diRegistrations = new List<string>();

            foreach (var group in byInterface)
            {
                var models = group.OrderBy(m => m.Target, StringComparer.Ordinal).ToList();
                if (models.Count < 2)
                    continue;

                foreach (var src in models)
                {
                    foreach (var dst in models)
                    {
                        if (src.Target == dst.Target)
                            continue;

                        // Mappings point "inward": emitted only by the project that owns the
                        // destination type, when the source type can be named here.
                        if (!policy.CanEmitMapping(src, dst, compilation))
                            continue;

                        var commonProps = GetCommonProperties(src, dst);
                        if (commonProps.Count == 0)
                            continue;

                        emittedModelNamespaces.Add(GetModelNamespace(src));
                        emittedModelNamespaces.Add(GetModelNamespace(dst));

                        string mapperClassName = $"{src.Target}To{dst.Target}Mapper";
                        string fieldName = $"_{ToCamelCase(src.Target)}To{dst.Target}Mapper";
                        string mapperSealed = src.IsSimpleMapping ? "sealed " : string.Empty;
                        bool emitMapperClass = NeedsMapperClass(src, dst);

                        if (emitMapperClass)
                        {
                            if (emittedMapperClasses.Add(mapperClassName))
                            {
                                // Duplicate src->dst pairs (same targets declared on multiple interfaces)
                                // merge into one partial class; [GeneratedCode] is AllowMultiple=false, so
                                // only the first part carries it.
                                mapperClasses.AppendLine($"    {GeneratorMetadata.AttributeLine}");
                            }
                            // IMapper<Src,Dst> is implemented only when DI is enabled: the
                            // registration is its only consumer, and the class is otherwise internal.
                            bool hasDi = (src.MappingTypes & MappingTypesDependencyInjection) != 0
                                || (dst.MappingTypes & MappingTypesDependencyInjection) != 0;
                            string mapperInterface = hasDi ? $" : global::CSteroid.IMapper<{src.Target}, {dst.Target}>" : string.Empty;
                            mapperClasses.AppendLine($"    internal {mapperSealed}partial class {mapperClassName}{mapperInterface}");
                            mapperClasses.AppendLine("    {");
                            if (!src.IsSimpleMapping)
                            {
                                mapperClasses.AppendLine($"        private static global::System.Func<{src.Target}, {dst.Target}>? _customMapFunc;");
                                mapperClasses.AppendLine();
                                mapperClasses.AppendLine($"        static {mapperClassName}()");
                                mapperClasses.AppendLine("        {");
                                mapperClasses.AppendLine("            ConfigureMapping((x) => _customMapFunc = x);");
                                mapperClasses.AppendLine("        }");
                                mapperClasses.AppendLine();
                                mapperClasses.AppendLine($"        static partial void ConfigureMapping(global::System.Action<global::System.Func<{src.Target}, {dst.Target}>?> customMapping);");
                                mapperClasses.AppendLine();
                            }
                            mapperClasses.AppendLine($"        /// <summary>Maps a <see cref=\"{src.Target}\"/> to a <see cref=\"{dst.Target}\"/>.</summary>");
                            mapperClasses.AppendLine($"        /// <param name=\"source\">The source <see cref=\"{src.Target}\"/>.</param>");
                            mapperClasses.AppendLine($"        /// <returns>A new <see cref=\"{dst.Target}\"/>.</returns>");
                            mapperClasses.AppendLine($"        public {dst.Target} Map({src.Target} source)");
                            mapperClasses.AppendLine("        {");
                            if (src.IsSimpleMapping)
                            {
                                mapperClasses.AppendLine("            return MapCore(source);");
                            }
                            else
                            {
                                mapperClasses.AppendLine("            if (_customMapFunc is not null)");
                                mapperClasses.AppendLine("                return _customMapFunc(source);");
                                mapperClasses.AppendLine();
                                mapperClasses.AppendLine("            return DefaultMap(source);");
                            }
                            mapperClasses.AppendLine("        }");
                            mapperClasses.AppendLine();
                            mapperClasses.AppendLine($"        /// <summary>Maps a <see cref=\"{src.Target}\"/> to a <see cref=\"{dst.Target}\"/> using the default mapping.</summary>");
                            mapperClasses.AppendLine($"        /// <param name=\"source\">The source <see cref=\"{src.Target}\"/>.</param>");
                            mapperClasses.AppendLine($"        /// <returns>A new <see cref=\"{dst.Target}\"/>.</returns>");
                            mapperClasses.AppendLine($"        public static {dst.Target} DefaultMap({src.Target} source)");
                            mapperClasses.AppendLine("        {");
                            if (src.IsSimpleMapping)
                            {
                                mapperClasses.AppendLine("            return MapCore(source);");
                                mapperClasses.AppendLine("        }");
                                mapperClasses.AppendLine();
                                mapperClasses.AppendLine($"        [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
                                mapperClasses.AppendLine($"        internal static {dst.Target} MapCore({src.Target} source)");
                                mapperClasses.AppendLine("        {");
                            }
                            mapperClasses.AppendLine($"            return {BuildMappingInitializer(src, dst, commonProps, targetNames, nestedGraph, "source", "            ")};");
                            mapperClasses.AppendLine("        }");

                            bool generateProjection = (src.MappingTypes & MappingTypesProjectionExpression) != 0;
                            if (generateProjection)
                            {
                                int incompatibleFlags = (src.MappingTypes | dst.MappingTypes) & (MappingTypesDependencyInjection | MappingTypesExplicitCast);
                                if (incompatibleFlags != 0)
                                {
                                    var descriptor = new DiagnosticDescriptor(
                                        "CSG101",
                                        "Incompatible mapping flags with ProjectionExpression",
                                        $"ProjectionExpression cannot be combined with DependencyInjection or ExplicitCast on mapping pair {src.Target} -> {dst.Target}.",
                                        "CSteroid",
                                        DiagnosticSeverity.Warning,
                                        true);
                                    spc.ReportDiagnostic(Diagnostic.Create(descriptor, Location.None));
                                }

                                mapperClasses.AppendLine();
                                mapperClasses.AppendLine($"        /// <summary>Gets an expression that projects a <see cref=\"{src.Target}\"/> to a <see cref=\"{dst.Target}\"/>.</summary>");
                                mapperClasses.AppendLine($"        public static global::System.Linq.Expressions.Expression<global::System.Func<{src.Target}, {dst.Target}>> ProjectionExpression {{ get; }} =");
                                mapperClasses.AppendLine($"            source => new {dst.Target}()");
                                mapperClasses.AppendLine("            {");

                                var visiting = new HashSet<string>(StringComparer.Ordinal) { src.Target };
                                foreach (var prop in commonProps.OrderBy(p => p.Name, StringComparer.Ordinal))
                                {
                                    var expression = GetPropertyProjectionExpression(prop, $"source.{prop.Name}", targetNames, targetInfo, visiting);
                                    mapperClasses.AppendLine($"                {prop.Name} = {expression},");
                                }

                                mapperClasses.AppendLine("            };");

                                projectionMethods.AppendLine($"        /// <summary>Projects a <see cref=\"{src.Target}\"/> query to <see cref=\"{dst.Target}\"/>.</summary>");
                                projectionMethods.AppendLine($"        /// <param name=\"query\">The source query.</param>");
                                projectionMethods.AppendLine($"        /// <returns>A query whose selection projects to <see cref=\"{dst.Target}\"/>.</returns>");
                                projectionMethods.AppendLine($"        internal static global::System.Linq.IQueryable<{dst.Target}> ProjectTo{dst.Target}(this global::System.Linq.IQueryable<{src.Target}> query)");
                                projectionMethods.AppendLine("        {");
                                projectionMethods.AppendLine($"            return query.Select({mapperClassName}.ProjectionExpression);");
                                projectionMethods.AppendLine("        }");
                                projectionMethods.AppendLine();
                            }

                            mapperClasses.AppendLine("    }");
                            mapperClasses.AppendLine();
                        }

                        if (emitMapperClass
                            || (src.MappingTypes & (MappingTypesExtensionMethod | MappingTypesStatic | MappingTypesDependencyInjection)) != 0
                            || (dst.MappingTypes & MappingTypesDependencyInjection) != 0)
                        {
                            hasAnyMappings = true;
                        }

                        if ((src.MappingTypes & MappingTypesExtensionMethod) != 0)
                        {
                            if (!src.IsSimpleMapping && !mapperInstances.Any(m => m.fieldName == fieldName && m.mapperType == mapperClassName))
                            {
                                mapperInstances.Add((fieldName, mapperClassName));
                            }
                            extensionMethods.AppendLine($"        /// <summary>Maps a <see cref=\"{src.Target}\"/> to a <see cref=\"{dst.Target}\"/>.</summary>");
                            extensionMethods.AppendLine($"        /// <param name=\"item\">The source <see cref=\"{src.Target}\"/>.</param>");
                            extensionMethods.AppendLine($"        /// <returns>A new <see cref=\"{dst.Target}\"/>.</returns>");
                            extensionMethods.AppendLine($"        [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
                            extensionMethods.AppendLine($"        internal static {dst.Target} MapTo{dst.Target}(this {src.Target} item)");
                            extensionMethods.AppendLine("        {");
                            if (emitMapperClass)
                            {
                                if (src.IsSimpleMapping)
                                {
                                    extensionMethods.AppendLine($"            return {mapperClassName}.MapCore(item);");
                                }
                                else
                                {
                                    extensionMethods.AppendLine($"            return MappingHelpers.{fieldName}.Map(item);");
                                }
                            }
                            else
                            {
                                extensionMethods.AppendLine($"            return {BuildMappingInitializer(src, dst, commonProps, targetNames, nestedGraph, "item", "            ")};");
                            }
                            extensionMethods.AppendLine("        }");
                            extensionMethods.AppendLine();
                        }

                        if ((src.MappingTypes & MappingTypesStatic) != 0)
                        {
                            if (!src.IsSimpleMapping && !mapperInstances.Any(m => m.fieldName == fieldName && m.mapperType == mapperClassName))
                            {
                                mapperInstances.Add((fieldName, mapperClassName));
                            }
                            staticMethods.AppendLine($"        /// <summary>Maps a <see cref=\"{src.Target}\"/> to a <see cref=\"{dst.Target}\"/>.</summary>");
                            staticMethods.AppendLine($"        /// <param name=\"item\">The source <see cref=\"{src.Target}\"/>.</param>");
                            staticMethods.AppendLine($"        /// <returns>A new <see cref=\"{dst.Target}\"/>.</returns>");
                            staticMethods.AppendLine($"        [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
                            staticMethods.AppendLine($"        public static {dst.Target} MapTo{dst.Target}({src.Target} item)");
                            staticMethods.AppendLine("        {");
                            if (emitMapperClass)
                            {
                                if (src.IsSimpleMapping)
                                {
                                    staticMethods.AppendLine($"            return {mapperClassName}.MapCore(item);");
                                }
                                else
                                {
                                    staticMethods.AppendLine($"            return MappingHelpers.{fieldName}.Map(item);");
                                }
                            }
                            else
                            {
                                staticMethods.AppendLine($"            return {BuildMappingInitializer(src, dst, commonProps, targetNames, nestedGraph, "item", "            ")};");
                            }
                            staticMethods.AppendLine("        }");
                            staticMethods.AppendLine();
                        }

                        if ((src.MappingTypes & MappingTypesDependencyInjection) != 0 || (dst.MappingTypes & MappingTypesDependencyInjection) != 0)
                        {
                            diRegistrations.Add($"            global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions.AddSingleton<global::CSteroid.IMapper<{src.Target}, {dst.Target}>, {mapperClassName}>(services);");
                        }
                    }
                }
            }

            if (!hasAnyMappings)
            {
                return null;
            }

            if (emittedModelNamespaces.Contains(ModelsNamespace))
            {
                sb.AppendLine($"using {ModelsNamespace};");
            }

            foreach (var ns in emittedModelNamespaces.OrderBy(n => n, StringComparer.Ordinal))
            {
                if (ns != mappingNamespace && ns != ModelsNamespace)
                {
                    sb.AppendLine($"using {ns};");
                }
            }

            sb.AppendLine();
            sb.AppendLine($"namespace {mappingNamespace}");
            sb.AppendLine("{");

            if (mapperInstances.Count > 0)
            {
                sb.AppendLine($"    {GeneratorMetadata.AttributeLine}");
                sb.AppendLine("    internal static class MappingHelpers");
                sb.AppendLine("    {");
                foreach (var (fieldName, mapperType) in mapperInstances.OrderBy(m => m.fieldName, StringComparer.Ordinal).Distinct())
                {
                    sb.AppendLine($"        internal static readonly {mapperType} {fieldName} = new ();");
                }
                sb.AppendLine("    }");
                sb.AppendLine();
            }

            if (extensionMethods.Length > 0)
            {
                sb.AppendLine($"    {GeneratorMetadata.AttributeLine}");
                sb.AppendLine("    internal static class MappingExtensions");
                sb.AppendLine("    {");
                sb.Append(extensionMethods);
                sb.AppendLine("    }");
                sb.AppendLine();
            }

            if (staticMethods.Length > 0)
            {
                sb.AppendLine($"    {GeneratorMetadata.AttributeLine}");
                sb.AppendLine("    internal static class MappingMethods");
                sb.AppendLine("    {");
                sb.Append(staticMethods);
                sb.AppendLine("    }");
                sb.AppendLine();
            }

            if (projectionMethods.Length > 0)
            {
                sb.AppendLine($"    {GeneratorMetadata.AttributeLine}");
                sb.AppendLine("    internal static class ProjectionExtensions");
                sb.AppendLine("    {");
                sb.Append(projectionMethods);
                sb.AppendLine("    }");
                sb.AppendLine();
            }

            sb.Append(mapperClasses);

            if (diRegistrations.Count > 0)
            {
                sb.AppendLine($"    {GeneratorMetadata.AttributeLine}");
                sb.AppendLine("    public static class CSteroidServiceCollectionExtensions");
                sb.AppendLine("    {");
                sb.AppendLine("        public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddCSteroidMappings(this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
                sb.AppendLine("        {");
                foreach (var reg in diRegistrations.OrderBy(r => r, StringComparer.Ordinal).Distinct())
                {
                    sb.AppendLine(reg);
                }
                sb.AppendLine("            return services;");
                sb.AppendLine("        }");
                sb.AppendLine("    }");
            }

            sb.AppendLine("}");
            return sb.ToString();
        }

        #endregion

        #region Helpers

        private static void ReportCircularReferenceDiagnostics(SourceProductionContext spc, Dictionary<string, HashSet<string>> graph)
        {
            var cycles = FindAllCycles(graph);
            foreach (var cycle in cycles)
            {
                var cyclePath = string.Join(" -> ", cycle);
                var desc = new DiagnosticDescriptor(
                    "CSG100",
                    "Circular reference in model graph",
                    $"Circular reference detected: {cyclePath}",
                    "CSteroid",
                    DiagnosticSeverity.Warning,
                    true);
                spc.ReportDiagnostic(Diagnostic.Create(desc, Location.None));
            }
        }

        private static List<List<string>> FindAllCycles(Dictionary<string, HashSet<string>> graph)
        {
            var cycles = new List<List<string>>();
            var visited = new HashSet<string>(StringComparer.Ordinal);
            var recursionStack = new HashSet<string>(StringComparer.Ordinal);
            var path = new List<string>();

            foreach (var node in graph.Keys)
            {
                if (!visited.Contains(node))
                    FindCyclesDfs(node, graph, visited, recursionStack, path, cycles);
            }

            return cycles;
        }

        private static void FindCyclesDfs(string node, Dictionary<string, HashSet<string>> graph, HashSet<string> visited, HashSet<string> recursionStack, List<string> path, List<List<string>> cycles)
        {
            visited.Add(node);
            recursionStack.Add(node);
            path.Add(node);

            if (graph.TryGetValue(node, out var neighbors))
            {
                foreach (var neighbor in neighbors)
                {
                    if (!visited.Contains(neighbor))
                    {
                        FindCyclesDfs(neighbor, graph, visited, recursionStack, path, cycles);
                    }
                    else if (recursionStack.Contains(neighbor))
                    {
                        var cycleStart = path.IndexOf(neighbor);
                        var cycle = path.Skip(cycleStart).ToList();
                        cycle.Add(neighbor);
                        cycles.Add(cycle);
                    }
                }
            }

            path.RemoveAt(path.Count - 1);
            recursionStack.Remove(node);
        }

        private static string GetPropertyMappingExpression(IPropertySymbol prop, string sourceTarget, string destinationTarget, HashSet<string> targetNames, Dictionary<string, HashSet<string>> graph, string sourceParameter = "source")
        {
            if (TryGetNestedTarget(prop.Type, targetNames, out var nestedTarget))
            {
                if (IsInCycle(sourceTarget, nestedTarget, graph))
                    return $"/* TODO: circular reference – map manually */ {sourceParameter}.{prop.Name}";

                return $"{sourceParameter}.{prop.Name}";
            }

            if (TryGetCollectionElementTarget(prop.Type, targetNames, out var elementTarget, out var collectionKind))
            {
                if (IsInCycle(sourceTarget, elementTarget, graph))
                    return $"/* TODO: circular reference – map manually */ {sourceParameter}.{prop.Name}";

                if (collectionKind == "Array")
                    return $"{sourceParameter}.{prop.Name}?.ToArray()";

                if (collectionKind == "HashSet")
                    return $"{sourceParameter}.{prop.Name} is null ? null : new HashSet<{elementTarget}>({sourceParameter}.{prop.Name})";

                return $"{sourceParameter}.{prop.Name}?.ToList()";
            }

            return $"{sourceParameter}.{prop.Name}";
        }

        /// <summary>
        /// The mapper class is the single customization point (ConfigureMapping hook), so it is
        /// emitted whenever several entry methods would otherwise each need overriding, or when a
        /// feature requires it (DI registration, projection expression). Pairs whose source
        /// declares no mapping entry point at all (e.g. cast-only or flag-less reverse pairs)
        /// get no mapper class either: operators cannot be overridden or hooked by consumers,
        /// so the class would be dead weight and the initializer is inlined instead.
        /// Simple mappings never emit the mapper class unless DI or projection needs it —
        /// no customization is possible by assumption, so each entry point inlines its own copy.
        /// </summary>
        private static bool NeedsMapperClass(ModelInfo src, ModelInfo dst)
        {
            bool hasDi = (src.MappingTypes & MappingTypesDependencyInjection) != 0
                || (dst.MappingTypes & MappingTypesDependencyInjection) != 0;
            bool hasProjection = (src.MappingTypes & MappingTypesProjectionExpression) != 0;

            if (src.IsSimpleMapping)
                return hasDi || hasProjection;

            bool hasExtension = (src.MappingTypes & MappingTypesExtensionMethod) != 0;
            bool hasStatic = (src.MappingTypes & MappingTypesStatic) != 0;

            // Cast operators are not overridable, and a source with no mapping entry points at
            // all produces dead code — neither needs a mapper class, so the initializer is inlined.
            if (!hasExtension && !hasStatic && !hasDi && !hasProjection)
                return false;

            return true;
        }

        /// <summary>Builds "new Dst() { P = expr, ... }" at the given brace indentation.</summary>
        private static string BuildMappingInitializer(ModelInfo src, ModelInfo dst, List<IPropertySymbol> commonProps, HashSet<string> targetNames, Dictionary<string, HashSet<string>> graph, string sourceParameter, string indent)
        {
            var sb = new StringBuilder();
            sb.AppendLine($"new {dst.Target}()");
            sb.AppendLine(indent + "{");
            foreach (var prop in commonProps.OrderBy(p => p.Name, StringComparer.Ordinal))
            {
                var expression = GetPropertyMappingExpression(prop, src.Target, dst.Target, targetNames, graph, sourceParameter);
                sb.AppendLine($"{indent}    {prop.Name} = {expression},");
            }
            sb.Append(indent + "}");
            return sb.ToString();
        }

        private static string GetPropertyProjectionExpression(IPropertySymbol prop, string accessExpression, HashSet<string> targetNames, Dictionary<string, ModelInfo> targetInfo, HashSet<string> visiting)
        {
            if (TryGetNestedTarget(prop.Type, targetNames, out var nestedTarget))
            {
                if (visiting.Contains(nestedTarget))
                    return "null /* circular reference */";

                visiting.Add(nestedTarget);
                var initializer = BuildInlineInitializer(nestedTarget, accessExpression, targetNames, targetInfo, visiting);
                visiting.Remove(nestedTarget);

                return $"({accessExpression} == null ? null : {initializer})";
            }

            if (TryGetCollectionElementTarget(prop.Type, targetNames, out var elementTarget, out var collectionKind))
            {
                if (visiting.Contains(elementTarget))
                    return "null /* circular reference */";

                visiting.Add(elementTarget);
                var elementInitializer = BuildInlineInitializer(elementTarget, "x", targetNames, targetInfo, visiting);
                visiting.Remove(elementTarget);

                var projection = $"({accessExpression} == null ? null : {accessExpression}.Select(x => {elementInitializer}))";

                return collectionKind switch
                {
                    "Array" => projection + ".ToArray()",
                    "HashSet" => $"({accessExpression} == null ? null : new HashSet<{elementTarget}>({accessExpression}.Select(x => {elementInitializer})))",
                    _ => projection + ".ToList()"
                };
            }

            return accessExpression;
        }

        private static string BuildInlineInitializer(string targetName, string sourcePrefix, HashSet<string> targetNames, Dictionary<string, ModelInfo> targetInfo, HashSet<string> visiting)
        {
            var info = targetInfo[targetName];
            var sb = new StringBuilder();
            sb.AppendLine($"new {targetName}()");
            sb.AppendLine("            {");

            foreach (var prop in info.Properties.OrderBy(p => p.Name, StringComparer.Ordinal))
            {
                var access = $"{sourcePrefix}.{prop.Name}";
                var expression = GetPropertyProjectionExpression(prop, access, targetNames, targetInfo, visiting);
                sb.AppendLine($"                {prop.Name} = {expression},");
            }

            sb.AppendLine("            }");
            return sb.ToString();
        }

        #endregion
