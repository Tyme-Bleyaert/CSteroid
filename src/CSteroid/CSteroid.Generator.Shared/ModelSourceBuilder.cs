using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using static CSteroid.Generator.Shared.AttributeFormatter;
using static CSteroid.Generator.Shared.GeneratorConstants;
using static CSteroid.Generator.Shared.NestedTargets;
using static CSteroid.Generator.Shared.OutputConventions;
using static CSteroid.Generator.Shared.SourceTextHelper;

namespace CSteroid.Generator.Shared
{
    public static class ModelSourceBuilder
    {
        public static string GenerateModel(ModelInfo info, HashSet<string> targetNames, IReadOnlyDictionary<string, int> declarationCounts = null)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("#pragma warning disable CS8618, CS8669 // generated models: reference properties are intentionally uninitialized");
            sb.AppendLine("using System;");

            bool hasDataAnnotations = info.Properties.Any(p => p.GetAttributes().Any(a => IsDataAnnotation(a)));
            if (hasDataAnnotations && (info.ValidationType & ValidationTypeDataAnnotations) != 0)
            {
                sb.AppendLine("using System.ComponentModel.DataAnnotations;");
            }

            if ((info.OrmTarget & OrmTargetPostgreSQL) != 0 && info.Properties.Any(AttributeEmitter.IsPostgreKeyProperty))
            {
                sb.AppendLine("using System.ComponentModel.DataAnnotations;");
            }

            bool needsSchemaAnnotations =
                ((info.OrmTarget & OrmTargetEFCore) != 0 && (info.OrmTarget & OrmTargetPostgreSQL) == 0 && info.Properties.Any(p => p.GetAttributes().Any(a => IsSchemaAnnotation(a))))
                || ((info.OrmTarget & OrmTargetDapper) != 0 && (info.OrmTarget & OrmTargetPostgreSQL) == 0 && info.Properties.Any(p => p.GetAttributes().Any(a => IsColumnAnnotation(a))))
                || (info.OrmTarget & OrmTargetPostgreSQL) != 0;
            if (needsSchemaAnnotations)
            {
                sb.AppendLine("using System.ComponentModel.DataAnnotations.Schema;");
            }

            if ((info.OrmTarget & OrmTargetCosmosDB) != 0)
            {
                sb.AppendLine("using System.Text.Json.Serialization;");
            }

            if ((info.OrmTarget & OrmTargetMongoDB) != 0)
            {
                sb.AppendLine("using MongoDB.Bson.Serialization.Attributes;");
            }

            sb.AppendLine();
            sb.AppendLine($"namespace {GetModelNamespace(info)}");
            sb.AppendLine("{");

            string declarationKeyword = info.DeclarationType switch
            {
                DeclarationTypeRecord => "record",
                DeclarationTypeStruct => "struct",
                _ => "class"
            };

            // Sealed fits the Simple = non-overridable contract and enables devirtualization.
            // Structs are implicitly sealed (the 'sealed' keyword is invalid there), and ORM
            // models (virtual navigation properties, EF lazy-loading proxies) must stay unsealed.
            bool isSimpleNonOrm = info.IsSimpleMapping && info.OrmTarget == 0;
            bool canSeal = isSimpleNonOrm && declarationKeyword != "struct";

            // 'partial' is the merge mechanism, not an extensibility hook: it is required when
            // the same target is declared more than once, and when cast operators apply (the
            // mapping generator merges its operator part into the class). Only a sole-declared,
            // non-cast Simple model can be emitted as a closed (non-partial) class.
            bool hasCastFlags = (info.MappingTypes & (MappingTypesImplicitCast | MappingTypesExplicitCast)) != 0;
            int declarationCount = 0;
            bool isSoleDeclaration = declarationCounts != null && declarationCounts.TryGetValue(info.Target, out declarationCount) && declarationCount == 1;
            bool emitClosed = isSimpleNonOrm && isSoleDeclaration && !hasCastFlags;

            string modifiers = emitClosed
                ? (declarationKeyword == "struct" ? "" : "sealed ")
                : (canSeal ? "sealed " : "");
            string partialModifier = emitClosed ? "" : "partial ";

            sb.AppendLine($"    {GeneratorMetadata.AttributeLine}");
            sb.AppendLine($"    public {modifiers}{partialModifier}{declarationKeyword} {info.Target}");
            sb.AppendLine("    {");

            foreach (var prop in info.Properties)
            {
                var docXml = GetPropertyDocumentation(prop, info.InterfaceSymbol);
                EmitXmlDoc(sb, docXml, "        ");

                AttributeEmitter.EmitAttributes(sb, info, prop);

                if ((info.OrmTarget & OrmTargetEFCore) != 0 && IsNavigationProperty(prop, targetNames))
                {
                    string typeName = prop.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                    sb.AppendLine($"        public virtual {typeName} {prop.Name} {{ get; set; }}");
                    continue;
                }

                string typeName2 = prop.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                sb.AppendLine($"        public {typeName2} {prop.Name} {{ get; set; }}");
            }

            if ((info.OrmTarget & OrmTargetEFCore) != 0 && info.DeclarationType != DeclarationTypeStruct)
            {
                sb.AppendLine();
                sb.AppendLine($"        private {info.Target}() {{ }}");
            }

            if ((info.OrmTarget & OrmTargetDapper) != 0 && info.Properties.Count > 0)
            {
                sb.AppendLine();
                var parameters = info.Properties.Select(p => $"{p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)} {ToCamelCase(p.Name)}").ToList();
                var assignments = info.Properties.Select(p => $"            {p.Name} = {ToCamelCase(p.Name)};").ToList();
                sb.AppendLine($"        public {info.Target}({string.Join(", ", parameters)})");
                sb.AppendLine("        {");
                foreach (var assignment in assignments)
                {
                    sb.AppendLine(assignment);
                }
                sb.AppendLine("        }");
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        private static bool IsNavigationProperty(IPropertySymbol prop, HashSet<string> targetNames)
        {
            return TryGetNestedTarget(prop.Type, targetNames, out _) || TryGetCollectionElementTarget(prop.Type, targetNames, out _, out _);
        }
    }
}
