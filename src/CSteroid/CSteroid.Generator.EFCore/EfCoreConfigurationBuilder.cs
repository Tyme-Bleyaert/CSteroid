using System;
using System.Collections.Generic;
using System.Linq;
using Microsoft.CodeAnalysis;
using CSteroid.Generator.Shared;
using static CSteroid.Generator.Shared.OutputConventions;

namespace CSteroid.Generator.EFCore
{
    /// <summary>
    /// Emits a partial <c>IEntityTypeConfiguration&lt;T&gt;</c> class per generated EF Core
    /// model. The user implements the <c>static partial void ConfigureEntity</c> hook in a
    /// matching partial to add fluent configuration (hasKey, conversions, indices, ...).
    /// Emitted only when EntityFrameworkCore is referenced: the interface and
    /// <c>EntityTypeBuilder</c> must resolve in the consumer compilation.
    /// </summary>
    internal static class EfCoreConfigurationBuilder
    {
        private const string ConfigurationNamespace = "CSteroid.Generated.EFCore";

        public static bool CanEmit(Compilation compilation)
        {
            return compilation.GetTypeByMetadataName("Microsoft.EntityFrameworkCore.IEntityTypeConfiguration`1") is not null
                && compilation.GetTypeByMetadataName("Microsoft.EntityFrameworkCore.Metadata.Builders.EntityTypeBuilder`1") is not null;
        }

        public static string GenerateConfiguration(ModelInfo info)
        {
            var modelNamespace = GetModelNamespace(info);
            var sb = new System.Text.StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("using System;");
            sb.AppendLine("using Microsoft.EntityFrameworkCore;");
            sb.AppendLine("using Microsoft.EntityFrameworkCore.Metadata.Builders;");
            if (modelNamespace != ConfigurationNamespace)
            {
                sb.AppendLine($"using {modelNamespace};");
            }
            sb.AppendLine();
            sb.AppendLine($"namespace {ConfigurationNamespace}");
            sb.AppendLine("{");
            sb.AppendLine($"    {GeneratorMetadata.AttributeLine}");
            sb.AppendLine($"    public partial class {info.Target}Configuration : global::Microsoft.EntityFrameworkCore.IEntityTypeConfiguration<{info.Target}>");
            sb.AppendLine("    {");
            sb.AppendLine($"        public void Configure(global::Microsoft.EntityFrameworkCore.Metadata.Builders.EntityTypeBuilder<{info.Target}> builder)");
            sb.AppendLine("        {");
            sb.AppendLine($"            ConfigureEntity(builder);");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine($"        static partial void ConfigureEntity(global::Microsoft.EntityFrameworkCore.Metadata.Builders.EntityTypeBuilder<{info.Target}> builder);");
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        public static string GetConfigurationHintPath(ModelInfo info)
        {
            return $"{ConfigurationNamespace.Replace('.', '/')}/{info.Target}Configuration.g.cs";
        }
    }
}
